router = APIRouter(prefix='/api/telephony', tags=['Téléphonie'])
HANGUP = '<?xml version="1.0" encoding="UTF-8"?><Response><Hangup /></Response>'


class Reservation(BaseModel):
    model_config = ConfigDict(extra='forbid')
    id: UUID
    campaign_id: UUID | None = None
    # Optional only for the preceding browser delivery. New clients always send
    # their explicit dialled number; it is never silently replaced by the test target.
    destination: str | None = Field(default=None, max_length=40)

    @field_validator('destination')
    @classmethod
    def explicit_number(cls, value):
        if value is None:
            raise ValueError('Numéro requis')
        return value


def profile(request):
    value = getattr(request.app.state, 'voice_profile', None)
    if value is None:
        raise HTTPException(503, 'Les appels ne sont pas activés.')
    return value


def caller(db, request, configured):
    actor = identity.authenticate(db, request)
    if not isinstance(configured, ManualVoiceProfile) and actor['role'] != 'admin':
        raise HTTPException(403, 'Les appels ne sont pas activés pour votre compte.')
    return actor


@router.get('/active-calls')
def active_calls(request: Request):
    with request.app.state.engine.begin() as db:
        identity.admin(db, request)
        rows = identity.query(db, '''SELECT i.id,i.destination,i.state,i.created_at,i.consumed_at,
            u.display_name AS actor_name FROM staging.voice_intents i
            JOIN staging.identity_users u ON u.id=i.actor_id
            WHERE i.state IN ('reserved','authorized','ringing','answered')
              AND (i.state<>'reserved' OR i.expires_at>clock_timestamp())
            ORDER BY i.created_at,i.id''').mappings().all()
        return {'items': [dict(row) for row in rows], 'active_count': len(rows),
                'answered_count': sum(row['state'] == 'answered' for row in rows)}


@router.get('/test/session')
def session(request: Request):
    # Read-only recovery after navigation, reload, or a lost reservation response.
    # A token is never returned or regenerated by this endpoint.
    with request.app.state.engine.begin() as db:
        actor = identity.authenticate(db, request)
        row = identity.query(db, '''SELECT * FROM staging.voice_intents
            WHERE actor_id=:actor AND state IN ('reserved','authorized','ringing','answered')
              AND (state<>'reserved' OR expires_at>clock_timestamp())
            ORDER BY created_at DESC LIMIT 1''', actor=actor['id']).mappings().first()
        active = service.public(row) if row else None
        if active is not None:
            active['owned_session'] = row['session_hash'] == actor['session_hash']
    configured = getattr(request.app.state, 'voice_profile', None)
    can_call = bool(configured and (isinstance(configured, ManualVoiceProfile) or actor['role'] == 'admin'))
    return {'enabled': bool(can_call and getattr(request.app.state, 'voice_calling_enabled', False)),
            'destination': getattr(configured, 'approved_destination', None),
            'max_duration_seconds': call_duration(configured), 'active': active}


@router.post('/test/intents', dependencies=[Depends(same_origin)], status_code=201)
def reserve(body: Reservation, request: Request):
    if not getattr(request.app.state, 'voice_calling_enabled', False):
        raise HTTPException(503, 'Les appels ne sont pas activés.')
    configured = profile(request)
    # Authenticate before charging a shared budget. Release the connection before
    # the limiter's independent transaction; authenticate again before mutation.
    with request.app.state.engine.begin() as db:
        actor = caller(db, request, configured)
        budget_actor = str(actor['id'])
    identity.limited(request.app.state.engine, 'voice-reserve', budget_actor,
                     limit=30, seconds=60, global_limit=600, authenticated=True)
    try:
        with request.app.state.engine.begin() as db:
            actor = caller(db, request, configured)
            row = service.reserve(db, actor, body.id, configured, body.destination,campaign_id=body.campaign_id)
            payload = service.public(row)
            actor_id = actor['id']
    except IntegrityError:
        raise HTTPException(409, 'Un appel est déjà réservé ou en cours pour cet utilisateur ou ce destinataire.') from None
    # No token is issued until the durable reservation transaction has committed.
    return {'intent': payload, 'token': browser_token(configured, actor_id, body.id)}


